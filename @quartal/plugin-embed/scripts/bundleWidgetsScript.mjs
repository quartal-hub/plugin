// Bundles `src/script/widgetsScript.ts` (the `widgets.js` every plugin serves) with esbuild and writes
// it as a string constant to the generated `src/script/widgetsScriptSource.ts`, so the plugin runtime
// can serve it on any host (no file system needed).
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const result = await build({
  entryPoints: [join(root, "src/script/widgetsScript.ts")],
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  write: false,
  legalComments: "none",
});
const code = result.outputFiles[0].text.trim();

await writeFile(
  join(root, "src/script/widgetsScriptSource.ts"),
  "// Generated by scripts/bundleWidgetsScript.mjs — do not edit.\n" +
    "/** The minified `widgets.js` bundle, with the config placeholder still in it. */\n" +
    `export const WIDGETS_SCRIPT_SOURCE: string = ${JSON.stringify(code)};\n`,
);
console.log(`widgets.js: ${code.length} bytes minified`);
